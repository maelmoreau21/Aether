export type StatParams = Record<string, string | number>;
export function translate(language: string, key: StatKey, params: StatParams = {}): string {
  const table: Record<StatKey, string> = language === 'en' ? dictionaries.en : dictionaries.fr;
  return Object.entries(params).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), table[key] ?? fr[key] ?? key);
}
