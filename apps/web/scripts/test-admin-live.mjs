import { chromium } from 'playwright';
import assert from 'node:assert/strict';

const origin = process.env.MEDIA_TEST_ORIGIN;
if (!origin || !process.env.MEDIA_TEST_ROOT) throw new Error('Use the Rust browser_admin harness.');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const login = await page.request.post(`${origin}/api/v1/auth/login`, { headers: { origin }, data: { login: 'browser-admin', password: 'disposable browser fixture password' } });
  assert.equal(login.status(), 200);
  const { csrfToken } = await login.json();
  const libraryResponse = await page.request.post(`${origin}/api/v1/admin/libraries`, { headers: { origin, 'x-csrf-token': csrfToken }, data: { name: 'Films de test', kind: 'films', nodeId: 'local', root: process.env.MEDIA_TEST_ROOT, enabled: true, userIds: [] } });
  assert.equal(libraryResponse.status(), 201);
  await page.goto(`${origin}/app/admin/libraries/#users-section`);
  const accounts = page.locator('#users-section');
  await accounts.getByLabel('Identifiant', { exact: true }).fill('browser-viewer');
  await accounts.getByLabel('Nom affiché', { exact: true }).fill('Compte de test');
  await accounts.getByLabel('Mot de passe (15 à 128 caractères)', { exact: true }).fill('disposable viewer account secret');
  await accounts.getByRole('button', { name: 'Créer le compte', exact: true }).click();
  await accounts.getByRole('row').filter({ hasText: 'browser-viewer' }).waitFor();
  await page.locator('.admin-sidebar a[href$="#groups-section"]').click();
  const groups = page.locator('#groups-section');
  await groups.getByLabel('Nom', { exact: true }).fill('Famille de test');
  await groups.getByLabel('Membre : Compte de test', { exact: true }).check();
  await groups.getByLabel('Bibliothèque autorisée : Films de test', { exact: true }).check();
  await groups.getByRole('button', { name: 'Enregistrer', exact: true }).click();
  await groups.getByRole('heading', { name: 'Famille de test' }).waitFor();
  await page.locator('.admin-sidebar a[href$="#tasks-section"]').click();
  const tasks = page.locator('#tasks-section');
  await tasks.getByRole('link', { name: 'Configurer Indexer Films de test' }).click();
  await tasks.getByRole('button', { name: 'Ajouter un déclencheur' }).click();
  await page.getByRole('dialog').getByLabel('Toutes les', { exact: true }).fill('1');
  await page.getByRole('dialog').getByLabel('Unité', { exact: true }).selectOption('60');
  await page.getByRole('dialog').getByRole('button', { name: 'Enregistrer', exact: true }).click();
  await tasks.getByText('Déclencheur enregistré.', { exact: true }).waitFor();
  await tasks.getByRole('button', { name: 'Exécuter Indexer Films de test', exact: true }).click();
  await tasks.getByText('Dernier scan connu : Terminé', { exact: true }).waitFor();
  await tasks.getByRole('button', { name: 'Supprimer le déclencheur' }).click();
  await tasks.getByText(/Aucun déclencheur actif/).waitFor();
  assert.deepEqual(await (await page.request.get(`${origin}/api/v1/admin/tasks/schedules`)).json(), []);
  await page.locator('.admin-sidebar a[href$="#api-keys-section"]').click();
  const keys = page.locator('#api-keys-section');
  await keys.getByLabel('Nom', { exact: true }).fill('Catalogue de test');
  const users = await (await page.request.get(`${origin}/api/v1/admin/users`)).json();
  const viewer = users.users.find(user => user.login === 'browser-viewer');
  await keys.getByLabel('Propriétaire').selectOption(viewer.id);
  await keys.getByLabel('Films de test', { exact: true }).check();
  await keys.getByRole('button', { name: 'Créer la clé', exact: true }).click();
  const tokenBox = keys.getByLabel('Nouvelle clé API', { exact: true });
  await tokenBox.waitFor();
  const token = await tokenBox.inputValue();
  const integration = await page.request.get(`${origin}/api/v1/integrations/catalog`, { headers: { Authorization: `Bearer ${token}` } });
  assert.equal(integration.status(), 200);
  await keys.getByRole('button', { name: 'Masquer la clé' }).click();
  page.once('dialog', dialog => dialog.accept());
  await keys.getByRole('button', { name: 'Révoquer', exact: true }).click();
  await keys.getByText('Révoquée', { exact: true }).waitFor();
  assert.equal((await page.request.get(`${origin}/api/v1/integrations/catalog`, { headers: { Authorization: `Bearer ${token}` } })).status(), 401);
  await page.locator('.admin-sidebar a[href$="#backups-section"]').click();
  const backups = page.locator('#backups-section');
  await backups.getByRole('heading', { name: 'Sauvegardes et base de données' }).waitFor();
  await backups.getByRole('button', { name: 'Créer une sauvegarde', exact: true }).click();
  await backups.getByText('Sauvegarde complète créée et chiffrée.', { exact: true }).waitFor();
  const archiveLink = backups.getByRole('link', { name: 'Télécharger', exact: true }).first();
  const download = await page.request.get(origin + await archiveLink.getAttribute('href'));
  assert.equal(download.status(), 200);
  assert.equal((await download.body()).subarray(0, 8).toString(), 'MDBK0001');
  await backups.getByLabel('Activer les sauvegardes automatiques').check();
  await backups.getByLabel('Intervalle en minutes', { exact: true }).fill('1440');
  await backups.getByRole('button', { name: 'Enregistrer la planification', exact: true }).click();
  await backups.getByText('Planification enregistrée.', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.mobile-menu-toggle').click();
  await page.locator('.admin-sidebar a[href$="#groups-section"]').click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '../../docs/evidence/admin-live-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: '../../docs/evidence/admin-live-desktop.png', fullPage: true });
  await page.goto(`${origin}/app/admin/libraries/#tasks-section?task=backup`);
  await page.getByRole('button', { name: 'Modifier le déclencheur' }).click();
  await page.getByRole('dialog').getByLabel('Toutes les', { exact: true }).fill('2');
  await page.getByRole('dialog').getByLabel('Unité', { exact: true }).selectOption('60');
  await page.getByRole('dialog').getByRole('button', { name: 'Enregistrer', exact: true }).click();
  await page.getByText('Déclencheur enregistré.', { exact: true }).waitFor();
  assert.equal((await (await page.request.get(`${origin}/api/v1/admin/backups`)).json()).schedule.intervalMinutes, 120);
  await page.getByRole('button', { name: 'Exécuter Sauvegarder le serveur' }).click();
  await page.getByText('Sauvegarde créée.', { exact: true }).waitFor();
  assert.equal((await (await page.request.get(`${origin}/api/v1/admin/backups`)).json()).archives.length, 2);
  await page.getByRole('button', { name: 'Supprimer le déclencheur' }).click();
  await page.getByText(/Aucun déclencheur actif/).waitFor();
  assert.equal((await (await page.request.get(`${origin}/api/v1/admin/backups`)).json()).schedule.enabled, false);
  await page.goto(`${origin}/app/settings/#playback`);
  await page.getByLabel('Décalage audio (secondes)', { exact: true }).fill('1.5');
  await page.getByLabel('Décalage des sous-titres (secondes)', { exact: true }).fill('-2');
  const offsetSaved = page.waitForResponse(r => r.url().endsWith('/preferences') && r.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Enregistrer les décalages' }).click();
  assert.equal((await offsetSaved).status(), 204);
  assert.deepEqual((await (await page.request.get(`${origin}/api/v1/preferences`)).json()).offsets, { audio: 1.5, subtitle: -2 });
  await page.reload();
  assert.equal(await page.getByLabel('Décalage audio (secondes)', { exact: true }).inputValue(), '1.5');
  assert.deepEqual(errors, []);
  console.log('Real Core/SQLite administration browser flow passed: account, group, schedule, scan, key creation/revocation, task trigger deletion, backup task actions, persisted playback offsets, responsive and JS checks.');
} finally { await browser.close(); }
